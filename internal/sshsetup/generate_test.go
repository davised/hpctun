func TestResolveHostNamesIncludesTunnelGateway(t *testing.T) {
	in := Input{Gateway: "shell", TunnelGateway: "mytun", SSH: config.SSH{User: "me", GatewayHost: "shell.example.org", Nodes: []string{"*.example.org"}}}
	in.ResolveHostNames(context.Background(), func(_ context.Context, h string) (map[string]string, error) {
		return map[string]string{"hostname": h + ".example.org"}, nil
	})
	if !slices.Equal(in.HostNames, []string{"mytun.example.org"}) {
		t.Fatalf("host names %q", in.HostNames)
	}
	if in.IsNode("mytun.example.org") || in.IsNode("mytun") {
		t.Fatal("the tunnel gateway is captured by the node block")
	}
}

// TestTunnelGatewayDestinationNotExcluded covers a tunnel_gateway that is a
// destination (user@host) rather than an alias: it is not a Host name, so
// it is neither resolved with ssh -G nor added to the node block's
// exclusions.
func TestTunnelGatewayDestinationNotExcluded(t *testing.T) {
	in := Input{Gateway: "shell", TunnelGateway: "me@tun.example.org", SSH: config.SSH{User: "me", GatewayHost: "shell.example.org", Nodes: []string{"*.example.org"}}}
	var asked []string
	in.ResolveHostNames(context.Background(), func(_ context.Context, h string) (map[string]string, error) {
		asked = append(asked, h)
		return map[string]string{"hostname": "tun.example.org"}, nil
	})
	if len(asked) != 0 || len(in.HostNames) != 0 {
		t.Fatalf("resolved %q, host names %q", asked, in.HostNames)
	}
	if ex := in.NodeExclusions(); slices.Contains(ex, "me@tun.example.org") {
		t.Fatalf("exclusions %q", ex)
	}
}

// writeTun writes text to hpctun_config and creates the sockets directory, as
// an approved change would.
func writeTun(t *testing.T, p Paths, text string) {
	t.Helper()
	c, err := TunConfigChange(p, text)
	if err != nil {
		t.Fatal(err)
	}
	if err := change.Apply([]change.Change{c}); err != nil {
		t.Fatal(err)
	}
	if err := EnsureSockets(p); err != nil {
		t.Fatal(err)
	}
}

func TestTunConfigChangeAndStale(t *testing.T) {
	home := t.TempDir()
	p := DefaultPaths(home)
	if stale, err := Stale(p, "x"); err != nil || !stale {
		t.Fatalf("missing file: %v %v", stale, err)
	}
	c, err := TunConfigChange(p, "x")
	if err != nil || c.Exists || c.Empty() {
		t.Fatalf("%+v %v", c, err)
	}
	if _, err := os.Stat(p.TunConfig); err == nil {
		t.Fatal("proposing a change wrote the file")
	}
	writeTun(t, p, "x")
	if err := EnsureSockets(p); err != nil {
		t.Fatal(err)
	}
	for path, want := range map[string]os.FileMode{p.TunConfig: 0o600, p.Sockets: 0o700, filepath.Dir(p.TunConfig): 0o700} {
		fi, err := os.Stat(path)
		if err != nil || fi.Mode().Perm() != want {
			t.Fatalf("%s: %v %v", path, fi, err)
		}
	}
	if stale, _ := Stale(p, "x"); stale {
		t.Fatal("stale after write")
	}
	if stale, _ := Stale(p, "y"); !stale {
		t.Fatal("not stale after change")
	}
	if c, _ := TunConfigChange(p, "x"); !c.Empty() {
		t.Fatal("rewriting identical text is not an empty change")
	}
}

