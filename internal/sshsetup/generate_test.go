func TestIsNode(t *testing.T) {
	in := Input{Gateway: "shell",
		SSH:         config.SSH{User: "me", GatewayHost: "shell.example.org", Nodes: []string{"*.example.org", "node*"}},
		UserAliases: []string{"node9"}}
	cases := map[string]bool{
		"web.example.org":   true,
		"NODE1":             true,
		"shell.example.org": false, // the gateway's own host name
		"shell":             false,
		"node9":             false, // configured by the user
		"chrom1":            false,
	}
	for host, want := range cases {
		if got := in.IsNode(host); got != want {
			t.Errorf("IsNode(%q) = %v", host, got)
		}
	}
}

func TestGenerateTunnelGatewayBlock(t *testing.T) {
	in := Input{Gateway: "shell", TunnelGateway: "shell-tunnels", Source: "~/.config/tun/config.toml",
		SSH: config.SSH{User: "me", GatewayHost: "shell.example.org", TunnelGatewayHost: "shell.example.org",
			Nodes: []string{"node*"}}}
	tunnels := strings.Replace(common, "sockets/%C", "sockets/tunnels-%C", 1)
	want := header +
		"\nHost shell\n    HostName shell.example.org\n" + common +
		"\nHost shell-tunnels\n    HostName shell.example.org\n" + tunnels +
		"\nHost node* !shell !shell.example.org !shell-tunnels\n    ProxyJump shell\n" + common
	if got := Generate(in); got != want {
		t.Fatalf("got\n%s\nwant\n%s", got, want)
	}
	if (Input{SSH: config.SSH{TunnelGatewayHost: "x.example.org"}}).Empty() {
		t.Fatal("a tunnel gateway block is not empty")
	}
}

