const common = `    User me
    ControlMaster auto
    ControlPath ~/.ssh/sockets/%C
    ControlPersist yes
    ServerAliveInterval 30
    ServerAliveCountMax 10
    AddKeysToAgent yes
`

const header = "# Generated by hpctun from ~/.config/tun/config.toml. Edits are overwritten;\n" +
	"# change the [ssh] table there and run `hpctun ssh-config sync`.\n"

func TestGenerateAllBlocks(t *testing.T) {
	in := Input{Gateway: "shell", Source: "~/.config/tun/config.toml",
		SSH: config.SSH{User: "me", GatewayHost: "shell.example.org", Transfer: "files",
			TransferHost: "files.example.org", Nodes: []string{"node*", "chrom*"}},
		UserAliases: []string{"chrom1", "web", "chrom1-x11"}}
	want := header +
		"\nHost shell\n    HostName shell.example.org\n" + common +
		"\nHost files\n    HostName files.example.org\n" + common +
		"\nHost node* chrom* !shell !shell.example.org !files !files.example.org !chrom1 !chrom1-x11\n    ProxyJump shell\n" + common
	if got := Generate(in); got != want {
		t.Fatalf("got\n%s\nwant\n%s", got, want)
	}
}

