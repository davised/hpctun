// TestResolveHostNamesExcludesUserAliasHosts covers a gateway alias the user
// defines (HostName login.example.org) with nodes = ["*.example.org"]:
// without the exclusion, ssh login.example.org would hop through the
// gateway to itself.
func TestResolveHostNamesExcludesUserAliasHosts(t *testing.T) {
	in := Input{Gateway: "hpc", Source: "src",
		SSH: config.SSH{User: "me", Transfer: "files", Nodes: []string{"*.example.org"}}}
	var asked []string
	sshG := func(_ context.Context, host string) (map[string]string, error) {
		asked = append(asked, host)
		switch host {
		case "hpc":
			return map[string]string{"hostname": "login.example.org"}, nil
		case "files":
			return nil, errors.New("no such alias")
		}
		return nil, nil
	}
	in.ResolveHostNames(context.Background(), sshG)
	if !slices.Equal(asked, []string{"hpc", "files"}) || !slices.Equal(in.HostNames, []string{"login.example.org"}) {
		t.Fatalf("asked %q, HostNames %q", asked, in.HostNames)
	}
	if in.IsNode("login.example.org") || !in.IsNode("n1.example.org") {
		t.Fatal("IsNode")
	}
	want := "\nHost *.example.org !hpc !files !login.example.org\n    ProxyJump hpc\n"
	if got := Generate(in); !strings.Contains(got, want) {
		t.Fatalf("got\n%s", got)
	}
}

func TestResolveHostNamesSkips(t *testing.T) {
	never := func(_ context.Context, host string) (map[string]string, error) {
		t.Fatalf("ssh -G %s", host)
		return nil, nil
	}
	// tun defines both aliases, so it knows their host names already.
	in := Input{Gateway: "shell", SSH: config.SSH{GatewayHost: "shell.example.org", Transfer: "files",
		TransferHost: "files.example.org", Nodes: []string{"n*"}}}
	in.ResolveHostNames(context.Background(), never)
	// No node block, nothing to exclude.
	in = Input{Gateway: "hpc", SSH: config.SSH{Transfer: "files"}}
	in.ResolveHostNames(context.Background(), never)
	if in.HostNames != nil {
		t.Fatal(in.HostNames)
	}
	// A host name equal to the alias adds nothing.
	in = Input{Gateway: "login.example.org", SSH: config.SSH{Nodes: []string{"*.example.org"}}}
	in.ResolveHostNames(context.Background(), func(context.Context, string) (map[string]string, error) {
		return map[string]string{"hostname": "LOGIN.example.org"}, nil
	})
	if in.HostNames != nil {
		t.Fatal(in.HostNames)
	}
}

// A config path with a newline cannot end the comment and add directives.
func TestGenerateSourceStaysOnOneLine(t *testing.T) {
	got := Generate(Input{Gateway: "shell", Source: "/tmp/x.toml\nHost *\n    ProxyCommand evil\n#"})
	if strings.Contains(got, "\nHost *\n    ProxyCommand evil") {
		t.Fatalf("directive injected:\n%s", got)
	}
	first, _, _ := strings.Cut(got, "\n")
	if first != `# Generated by hpctun from /tmp/x.toml\nHost *\n    ProxyCommand evil\n#. Edits are overwritten;` {
		t.Fatalf("first line %q", first)
	}
}

