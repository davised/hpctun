// TestKeychainLinesParseWithoutUseKeychain: an OpenSSH without UseKeychain
// (Homebrew's, on a Mac) checks every block's options, not only the blocks
// that match, and IgnoreUnknown only covers the scope it is read in. So the
// file must still parse for every host when UseKeychain is unknown; a
// stand-in unknown option plays that part here.
func TestKeychainLinesParseWithoutUseKeychain(t *testing.T) {
	if _, err := exec.LookPath("ssh"); err != nil {
		t.Skip("ssh not installed")
	}
	in := Input{Gateway: "shell", Source: "src", Keychain: true,
		SSH: config.SSH{User: "me", GatewayHost: "shell.example.org", Nodes: []string{"node*"}}}
	text := strings.ReplaceAll(Generate(in), "UseKeychain", "TunTestNoSuchOption")
	cfg := filepath.Join(t.TempDir(), "tun_config")
	os.WriteFile(cfg, []byte(text), 0o600)
	// As installed: included at the top of the user's own config.
	user := filepath.Join(t.TempDir(), "config")
	os.WriteFile(user, []byte("Include "+cfg+"\n\nHost mine\n    User you\n"), 0o600)
	for _, f := range []string{cfg, user} {
		for _, host := range []string{"shell", "node1", "github.com", "mine"} {
			if out, err := exec.Command("ssh", "-G", "-F", f, host).CombinedOutput(); err != nil {
				t.Errorf("ssh -G -F %s %s: %v\n%s", filepath.Base(f), host, err, out)
			}
		}
	}
}
